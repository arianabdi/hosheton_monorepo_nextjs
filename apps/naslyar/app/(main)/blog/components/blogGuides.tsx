const FARSI_DIGITS = ['۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹'];

export function toFarsiStepNumber(n: number): string {
    return String(n)
        .split('')
        .map((d) => FARSI_DIGITS[parseInt(d, 10)] ?? d)
        .join('');
}


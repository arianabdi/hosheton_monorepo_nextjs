export function useLocalizedCountries() {
    const { i18n } = useTranslation();
    return useMemo(() => {
        let names: Intl.DisplayNames | null = null;
        try {
            names = new Intl.DisplayNames([i18n.language || 'en'], { type: 'region' });
        } catch {
            names = new Intl.DisplayNames(['en'], { type: 'region' });
        }
        return COUNTRY_ISO.map((c) => ({
            value: c.value,
            label: names?.of(c.iso) || c.value,
        })).sort((a, b) => a.label.localeCompare(b.label, i18n.language));
    }, [i18n.language]);
}

export const countries = COUNTRY_ISO.map((c) => ({ value: c.value, label: c.value }));
